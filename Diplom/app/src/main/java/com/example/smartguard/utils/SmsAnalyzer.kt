    /**
     * Анализ SMS (полный)
     */
    fun analyze(text: String): SmsAnalysisResult {
        val lowerText = text.lowercase()
        val reasons = mutableListOf<String>()
        var maxConfidence = 0
        var detectedCategory = "safe"

        // 1. Проверяем по категориям
        for ((category, patterns) in PHISHING_PATTERNS) {
            var categoryMatches = 0

            for (pattern in patterns) {
                if (lowerText.contains(pattern)) {
                    categoryMatches++
                    if (reasons.size < 15) {
                        reasons.add("Найдено: \"$pattern\"")
                    }
                }
            }

            if (categoryMatches > 0) {
                val confidence = (categoryMatches * 25).coerceAtMost(85)
                if (confidence > maxConfidence) {
                    maxConfidence = confidence
                    detectedCategory = category
                }
            }
        }

        // 2. Проверяем регулярные выражения
        for (regexPattern in SUSPICIOUS_REGEX) {
            if (regexPattern.regex.containsMatchIn(lowerText)) {
                reasons.add(regexPattern.description)
                maxConfidence = (maxConfidence + 8).coerceAtMost(95)
            }
        }

        // 3. Дополнительные эвристики
        if (text.length < 20) {
            reasons.add("Очень короткое сообщение")
            maxConfidence = (maxConfidence + 5).coerceAtMost(95)
        }

        val exclamationCount = text.count { it == '!' }
        if (exclamationCount >= 3) {
            reasons.add("Много восклицательных знаков")
            maxConfidence = (maxConfidence + 5).coerceAtMost(95)
        }

        val isPhishing = maxConfidence >= 40

        return SmsAnalysisResult(
            isPhishing = isPhishing,
            category = if (isPhishing) detectedCategory else "safe",
            confidence = maxConfidence,
            reasons = reasons.distinct()
        )
    }

