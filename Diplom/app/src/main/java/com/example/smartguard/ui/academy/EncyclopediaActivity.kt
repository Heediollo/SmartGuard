class SchemeAdapter(
    private val schemes: List<ScamScheme>,
    private val onItemClick: (ScamScheme) -> Unit
) : RecyclerView.Adapter<SchemeAdapter.ViewHolder>() {

    inner class ViewHolder(view: View) : RecyclerView.ViewHolder(view) {
        val card: MaterialCardView = view.findViewById(R.id.cardScheme)
        val tvTitle: TextView = view.findViewById(R.id.tvSchemeTitle)
        val tvShortDesc: TextView = view.findViewById(R.id.tvSchemeShortDesc)
    }

    override fun onCreateViewHolder(parent: ViewGroup, viewType: Int): ViewHolder {
        val view = LayoutInflater.from(parent.context)
            .inflate(R.layout.item_scam_scheme, parent, false)
        return ViewHolder(view)
    }

    override fun onBindViewHolder(holder: ViewHolder, position: Int) {
        val scheme = schemes[position]
        holder.tvTitle.text = scheme.title
        holder.tvShortDesc.text = scheme.shortDesc
        holder.card.setOnClickListener { onItemClick(scheme) }
    }

    override fun getItemCount(): Int = schemes.size
}